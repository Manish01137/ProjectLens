// Turns /generate output into the single card shape (Project) the whole UI uses.
import { createHash } from "node:crypto";
import type { AppliedFilters, GeneratedIdea, Project } from "./validators";

const lastWeek = (i: GeneratedIdea) => (i.milestones.length ? Math.max(...i.milestones.map((m) => m.week)) : null);

/** Splits "Python, scikit-learn; FastAPI" or ["Python, React"] into clean items. */
export function techList(stack: string | string[]): string[] {
  const parts = (Array.isArray(stack) ? stack : [stack]).flatMap((s) => s.split(/[,;]/));
  return [...new Set(parts.map((s) => s.trim()).filter(Boolean))];
}

export function ideaToProject(idea: GeneratedIdea, applied: AppliedFilters | null, profileLevel: string): Project {
  const generated = idea.source === "generated";
  const id = generated
    ? `gen-${createHash("sha1").update(`${idea.inspired_by}|${idea.title}`).digest("hex").slice(0, 12)}`
    : `cat-${idea.inspired_by}`;
  return {
    id,
    core_problem_id: idea.inspired_by,
    title: idea.title,
    problem_statement: idea.problem_statement,
    domain: idea.domain,
    approach: applied?.approaches?.[0] ?? "",
    project_type: "",
    tech_stack: techList(idea.tech_stack).join(", "),
    level: applied?.levels?.[0] ?? profileLevel,
    duration_weeks: lastWeek(idea),
    matched_skills: idea.skills_used,
    match_score: 0,
    source: generated ? "Generated by ProjectLens" : "ProjectLens catalogue",
    kind: generated ? "generated" : "catalogue",
    skills_used: idea.skills_used,
    new_skill_to_learn: idea.new_skill_to_learn,
    milestones: idea.milestones,
    data_source: idea.data_source,
    why_it_fits: idea.why_it_fits,
    target_users: idea.target_users,
    inspired_by: idea.inspired_by,
    ...(idea.novelty_similarity !== undefined ? { novelty_similarity: idea.novelty_similarity } : {}),
  };
}

/** Core-problem ids a card "uses up", so they are never shown again in the conversation. */
export function coreIdsOf(p: Project): string[] {
  return [...new Set([p.core_problem_id, p.inspired_by].filter((x): x is string => Boolean(x)))];
}
